const LANG_LABELS = {
  en: "🇬🇧 English",
  ar: "🇸🇦 العربية",
  de: "🇩🇪 Deutsch"
};

function t(key) {
  const lang = getLang();
  return (translations[lang] && translations[lang][key]) || key;
}

function getLang() {
  return localStorage.getItem("wingen_lang") || "en";
}

function setLang(lang) {
  localStorage.setItem("wingen_lang", lang);
  applyLang();
}

function applyLang() {
  const lang = getLang();
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });

  const currentLabel = document.querySelector("#lang-toggle .lang-current");
  if (currentLabel) {
    currentLabel.textContent = LANG_LABELS[lang];
  }
  document.querySelectorAll(".lang-option").forEach((btn) => {
    btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
  });
}

function closeLangMenu() {
  const menu = document.getElementById("lang-menu");
  const toggleBtn = document.getElementById("lang-toggle");
  if (menu) menu.hidden = true;
  if (toggleBtn) toggleBtn.setAttribute("aria-expanded", "false");
}

document.addEventListener("DOMContentLoaded", () => {
  applyLang();
  const dropdown = document.querySelector(".lang-dropdown");
  const toggleBtn = document.getElementById("lang-toggle");
  const menu = document.getElementById("lang-menu");

  if (toggleBtn && menu) {
    toggleBtn.addEventListener("click", (e) => {
      e.stopPropagation();
      const isOpen = !menu.hidden;
      menu.hidden = isOpen;
      toggleBtn.setAttribute("aria-expanded", String(!isOpen));
    });

    menu.querySelectorAll(".lang-option").forEach((btn) => {
      btn.addEventListener("click", () => {
        setLang(btn.getAttribute("data-lang"));
        closeLangMenu();
      });
    });
  }

  document.addEventListener("click", (e) => {
    if (dropdown && !dropdown.contains(e.target)) closeLangMenu();
  });
  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape") closeLangMenu();
  });
});
